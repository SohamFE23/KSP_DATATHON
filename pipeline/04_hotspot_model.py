# ????????? Paths ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
ROOT     = Path(__file__).resolve().parent.parent
PROC_DIR = ROOT / "data" / "processed"

# ????????? Load ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def load_data() -> pd.DataFrame:
    for fname in ["risk_scores.csv", "district_features.csv", "karnataka_clean.csv"]:
        p = PROC_DIR / fname
        if p.exists():
            print(f"  [DATA] Loading {fname}")
            return pd.read_csv(p, low_memory=False)
    raise FileNotFoundError("No risk_scores.csv found. Run 03_risk_classifier.py first.")


def get_latest_year(df: pd.DataFrame) -> pd.DataFrame:
    """Get most recent year data for each district."""
    year_col = "YEAR" if "YEAR" in df.columns else df.columns[2]
    return df.sort_values(year_col).groupby("DISTRICT", as_index=False).last()


# ????????? DBSCAN Clustering ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def run_dbscan(df: pd.DataFrame) -> pd.DataFrame:
    """Run DBSCAN on lat/lon/crime_count to detect spatial hotspot clusters."""
    df = df.copy()

    # Need lat/lon
    if "LAT" not in df.columns or "LON" not in df.columns:
        print("  [WARN] LAT/LON columns missing ??? skipping DBSCAN spatial clustering")
        df["CLUSTER"] = 0
        return df

    crime_col = "TOTAL_CRIMES" if "TOTAL_CRIMES" in df.columns else df.select_dtypes("number").columns[0]

    features = df[["LAT", "LON", crime_col]].copy().fillna(0)
    scaler = StandardScaler()
    scaled = scaler.fit_transform(features)

    # eps=0.5 ??? roughly 0.5 std dev radius; min_samples=3
    db = DBSCAN(eps=0.5, min_samples=3, metric="euclidean")
    df["CLUSTER"] = db.fit_predict(scaled)

    n_clusters = len(set(df["CLUSTER"])) - (1 if -1 in df["CLUSTER"].values else 0)
    n_noise    = (df["CLUSTER"] == -1).sum()
    print(f"  [DBSCAN] {n_clusters} clusters found | {n_noise} noise points")

    return df


# ????????? Folium Maps ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

KARNATAKA_CENTER = [15.3173, 75.7139]
KARNATAKA_ZOOM   = 7

RISK_COLORS = {"HIGH": "#f85149", "MEDIUM": "#e3b341", "LOW": "#3fb950"}
CLUSTER_COLORS = [
    "#f85149", "#e3b341", "#58a6ff", "#3fb950", "#bc8cff",
    "#f0883e", "#39d353", "#79c0ff", "#ffa657", "#d2a8ff",
]


def _get_risk_label(row) -> str:
    for col in ["PREDICTED_RISK_LABEL", "RISK_LABEL"]:
        if col in row.index and pd.notna(row[col]):
            return str(row[col]).upper()
    return "MEDIUM"


def build_hotspot_map(df: pd.DataFrame) -> folium.Map:
    """Circle markers colored by cluster, sized by crime count."""
    m = folium.Map(
        location=KARNATAKA_CENTER, zoom_start=KARNATAKA_ZOOM,
        tiles="CartoDB dark_matter",
    )

    crime_col = "TOTAL_CRIMES" if "TOTAL_CRIMES" in df.columns else None
    max_crimes = df[crime_col].max() if crime_col else 1

    for _, row in df.iterrows():
        if pd.isna(row.get("LAT")) or pd.isna(row.get("LON")):
            continue

        risk  = _get_risk_label(row)
        color = RISK_COLORS.get(risk, "#58a6ff")
        cluster_id = int(row.get("CLUSTER", 0))
        c_color = CLUSTER_COLORS[cluster_id % len(CLUSTER_COLORS)] if cluster_id >= 0 else "#555555"

        crime_val = int(row[crime_col]) if crime_col else 0
        radius    = 6 + (crime_val / max_crimes) * 18

        popup_html = f"""
        <div style="font-family:Arial;font-size:13px;min-width:180px;">
          <b style="color:{color};">{row.get('DISTRICT','?')}</b><br>
          Risk: <b>{risk}</b><br>
          Total Crimes: <b>{crime_val:,}</b><br>
          Cluster: <b>{'Hotspot #'+str(cluster_id) if cluster_id>=0 else 'Isolated'}</b>
        </div>"""

        folium.CircleMarker(
            location=[row["LAT"], row["LON"]],
            radius=radius,
            color=c_color,
            fill=True,
            fill_color=color,
            fill_opacity=0.7,
            weight=2,
            popup=folium.Popup(popup_html, max_width=220),
            tooltip=f"{row.get('DISTRICT','?')} ??? {risk} RISK",
        ).add_to(m)

        # Pulsing ring for CRITICAL/HIGH zones
        if risk == "HIGH" and cluster_id >= 0:
            folium.Circle(
                location=[row["LAT"], row["LON"]],
                radius=15000,
                color="#f85149",
                fill=False,
                weight=1,
                opacity=0.4,
                dash_array="6 4",
            ).add_to(m)

    # Legend
    legend_html = """
    <div style="position:fixed;bottom:30px;left:30px;z-index:9999;
                background:#161b22;border:1px solid #30363d;border-radius:8px;
                padding:12px 16px;font-family:Arial;font-size:12px;color:#e6edf3;">
      <b>??????? Risk Level</b><br>
      <span style="color:#f85149;">??? HIGH</span>&nbsp;&nbsp;
      <span style="color:#e3b341;">??? MEDIUM</span>&nbsp;&nbsp;
      <span style="color:#3fb950;">??? LOW</span><br>
      <small style="color:#8b949e;">Dashed ring = Hotspot cluster</small>
    </div>"""
    m.get_root().html.add_child(folium.Element(legend_html))

    return m


def build_heatmap(df: pd.DataFrame) -> folium.Map:
    """HeatMap layer based on crime volume at each district centroid."""
    m = folium.Map(
        location=KARNATAKA_CENTER, zoom_start=KARNATAKA_ZOOM,
        tiles="CartoDB dark_matter",
    )

    crime_col = "TOTAL_CRIMES" if "TOTAL_CRIMES" in df.columns else None
    if crime_col is None:
        return m

    heat_data = [
        [row["LAT"], row["LON"], row[crime_col]]
        for _, row in df.iterrows()
        if pd.notna(row.get("LAT")) and pd.notna(row.get("LON"))
    ]

    HeatMap(
        heat_data,
        radius=25, blur=20, max_zoom=13,
        gradient={0.2: "#3fb950", 0.5: "#e3b341", 0.8: "#f85149", 1.0: "#ff0000"},
    ).add_to(m)

    return m


def build_choropleth_fallback(df: pd.DataFrame) -> folium.Map:
    """Choropleth using circle size + risk color (no GeoJSON needed)."""
    m = folium.Map(
        location=KARNATAKA_CENTER, zoom_start=KARNATAKA_ZOOM,
        tiles="CartoDB positron",
    )

    crime_col = "TOTAL_CRIMES" if "TOTAL_CRIMES" in df.columns else None
    if crime_col:
        max_val = df[crime_col].max() or 1
        colormap = cm.LinearColormap(
            ["#3fb950", "#e3b341", "#f85149"],
            vmin=0, vmax=max_val,
            caption="Total Crimes",
        )
        colormap.add_to(m)

    for _, row in df.iterrows():
        if pd.isna(row.get("LAT")) or pd.isna(row.get("LON")):
            continue
        crime_val = row[crime_col] if crime_col else 0
        color     = colormap(crime_val) if crime_col else "#58a6ff"

        folium.CircleMarker(
            location=[row["LAT"], row["LON"]],
            radius=10,
            color="white",
            weight=0.5,
            fill=True,
            fill_color=color,
            fill_opacity=0.85,
            tooltip=f"{row.get('DISTRICT','?')}: {int(crime_val):,} crimes",
        ).add_to(m)

    return m


# ????????? Static Cluster Plot ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def save_cluster_plot(df: pd.DataFrame):
    if "LAT" not in df.columns: return

    fig, ax = plt.subplots(figsize=(10, 8))
    fig.patch.set_facecolor("#0d1117")
    ax.set_facecolor("#0d1117")

    clusters = df["CLUSTER"].unique()
    for cl in sorted(clusters):
        mask = df["CLUSTER"] == cl
        color = "#555555" if cl == -1 else CLUSTER_COLORS[cl % len(CLUSTER_COLORS)]
        label = "Isolated" if cl == -1 else f"Cluster {cl}"
        ax.scatter(df.loc[mask, "LON"], df.loc[mask, "LAT"],
                   c=color, label=label, s=60, alpha=0.85, edgecolors="white", linewidths=0.3)

    crime_col = "TOTAL_CRIMES" if "TOTAL_CRIMES" in df.columns else None
    if crime_col:
        for _, row in df.nlargest(5, crime_col).iterrows():
            if pd.notna(row.get("LAT")):
                ax.annotate(row.get("DISTRICT","?"),
                            (row["LON"], row["LAT"]),
                            textcoords="offset points", xytext=(5, 5),
                            color="white", fontsize=7)

    ax.set_title("Karnataka District Crime Clusters (DBSCAN)", color="#e6edf3", fontsize=14)
    ax.set_xlabel("Longitude", color="#8b949e")
    ax.set_ylabel("Latitude", color="#8b949e")
    ax.tick_params(colors="#8b949e")
    ax.legend(facecolor="#161b22", edgecolor="#30363d", labelcolor="#e6edf3", fontsize=8)
    for sp in ax.spines.values(): sp.set_color("#30363d")

    out = PROC_DIR / "hotspot_clusters.png"
    plt.savefig(out, dpi=120, bbox_inches="tight", facecolor="#0d1117")
    plt.close()
    print(f"  [CHART] {out}")


# ????????? Main ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def main():
    print("\n" + "="*60)
    print("  STEP 04 ??? Hotspot Model (DBSCAN + Folium Maps)")
    print("="*60)

    df_full = load_data()
    df      = get_latest_year(df_full)
    print(f"  [DATA] {len(df)} districts for latest year")

    # DBSCAN clustering
    df = run_dbscan(df)

    # Save clustered CSV
    out_csv = PROC_DIR / "hotspot_clusters.csv"
    df.to_csv(out_csv, index=False)
    print(f"  [OUT] {out_csv}")

    # Build & save maps
    print("  Building Folium maps...")

    m1 = build_hotspot_map(df)
    m1.save(str(PROC_DIR / "karnataka_hotspot_map.html"))
    print(f"  [MAP] karnataka_hotspot_map.html")

    m2 = build_heatmap(df)
    m2.save(str(PROC_DIR / "karnataka_heatmap.html"))
    print(f"  [MAP] karnataka_heatmap.html")

    m3 = build_choropleth_fallback(df)
    m3.save(str(PROC_DIR / "karnataka_choropleth.html"))
    print(f"  [MAP] karnataka_choropleth.html")

    # Static chart
    save_cluster_plot(df)

    print("\n  [DONE] Hotspot model complete.")
    print("="*60 + "\n")


if __name__ == "__main__":
    main()

