import pandas as pd
import numpy as np
import warnings
warnings.filterwarnings("ignore")
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from pathlib import Path

try:
    from prophet import Prophet
    PROPHET_AVAILABLE = True
except ImportError:
    PROPHET_AVAILABLE = False
    print("  [WARN] Prophet not installed. Using linear extrapolation fallback.")

# ????????? Paths ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
ROOT     = Path(__file__).resolve().parent.parent
PROC_DIR = ROOT / "data" / "processed"

FORECAST_YEARS  = 3     # How many years to forecast ahead
MIN_DATA_POINTS = 4     # Min years of data needed per district

# ????????? Load ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def load_data() -> pd.DataFrame:
    for fname in ["district_features.csv", "karnataka_clean.csv", "risk_scores.csv"]:
        p = PROC_DIR / fname
        if p.exists():
            print(f"  [DATA] Loading {fname}")
            return pd.read_csv(p, low_memory=False)
    raise FileNotFoundError("No district data found. Run 02_feature_engineering.py first.")


# ????????? Forecast (Prophet) ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def prophet_forecast(dist_name: str, series: pd.Series, years: pd.Series, n_future: int) -> pd.DataFrame:
    """Fit Prophet model for one district and return forecast DataFrame."""
    prophet_df = pd.DataFrame({
        "ds": pd.to_datetime(years.astype(str) + "-01-01"),
        "y":  series.values.astype(float),
    }).dropna()

    if len(prophet_df) < MIN_DATA_POINTS:
        return pd.DataFrame()

    model = Prophet(
        yearly_seasonality=False,
        weekly_seasonality=False,
        daily_seasonality=False,
        changepoint_prior_scale=0.3,
        interval_width=0.80,
        uncertainty_samples=0,   # faster
    )
    model.fit(prophet_df)

    # Build future dates
    last_year = years.max()
    future_years = list(range(int(last_year) + 1, int(last_year) + n_future + 1))
    future_df = pd.DataFrame({"ds": pd.to_datetime([f"{y}-01-01" for y in future_years])})
    future_all = pd.concat([prophet_df[["ds"]], future_df], ignore_index=True)

    forecast = model.predict(future_all)
    forecast["DISTRICT"] = dist_name
    forecast["year"] = forecast["ds"].dt.year
    forecast["is_forecast"] = forecast["ds"].dt.year > last_year
    forecast["actual"] = None

    # Fill actual values
    year_to_actual = dict(zip(years.astype(int), series.values))
    forecast["actual"] = forecast["year"].map(year_to_actual)

    return forecast[["DISTRICT", "ds", "yhat", "yhat_lower", "yhat_upper",
                      "is_forecast", "year", "actual"]]


def linear_forecast(dist_name: str, series: pd.Series, years: pd.Series, n_future: int) -> pd.DataFrame:
    """Simple linear extrapolation fallback when Prophet not available."""
    x = years.values.astype(float)
    y = series.values.astype(float)

    if len(x) < 2:
        return pd.DataFrame()

    slope, intercept = np.polyfit(x, y, 1)
    last_year = int(years.max())
    future_years = list(range(last_year + 1, last_year + n_future + 1))
    all_years = list(years.astype(int)) + future_years
    preds = slope * np.array(all_years) + intercept

    rows = []
    year_to_actual = dict(zip(years.astype(int), series.values))
    for yr, pred in zip(all_years, preds):
        rows.append({
            "DISTRICT": dist_name,
            "ds": pd.Timestamp(f"{yr}-01-01"),
            "yhat": max(0, round(pred, 1)),
            "yhat_lower": max(0, round(pred * 0.85, 1)),
            "yhat_upper": max(0, round(pred * 1.15, 1)),
            "is_forecast": yr > last_year,
            "year": yr,
            "actual": year_to_actual.get(yr),
        })
    return pd.DataFrame(rows)


# ????????? Trend Direction ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def classify_trend(forecast_vals: pd.Series, historical_avg: float) -> str:
    if len(forecast_vals) == 0 or historical_avg == 0:
        return "STABLE"
    future_avg = forecast_vals.mean()
    pct_change = (future_avg - historical_avg) / historical_avg * 100
    if pct_change > 10:   return "INCREASING"
    elif pct_change < -10: return "DECREASING"
    else:                  return "STABLE"


# ????????? Chart ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def save_forecast_chart(all_forecasts: pd.DataFrame):
    crime_col = "yhat"
    top5 = (
        all_forecasts[~all_forecasts["is_forecast"]]
        .groupby("DISTRICT")[crime_col].mean()
        .nlargest(5).index.tolist()
    )

    fig, axes = plt.subplots(1, min(5, len(top5)), figsize=(16, 4), sharey=False)
    if len(top5) == 1: axes = [axes]
    fig.patch.set_facecolor("#0d1117")

    colors = ["#f85149", "#e3b341", "#58a6ff", "#3fb950", "#bc8cff"]

    for i, (dist, ax) in enumerate(zip(top5, axes)):
        df_d = all_forecasts[all_forecasts["DISTRICT"] == dist].sort_values("year")
        hist = df_d[~df_d["is_forecast"]]
        fore = df_d[df_d["is_forecast"]]

        ax.set_facecolor("#161b22")
        for sp in ax.spines.values(): sp.set_color("#30363d")
        ax.tick_params(colors="#8b949e", labelsize=7)
        ax.grid(True, alpha=0.15, color="#30363d")

        ax.plot(hist["year"], hist["yhat"], color=colors[i], linewidth=2, marker="o", markersize=4)
        if not fore.empty:
            ax.plot(fore["year"], fore["yhat"], color=colors[i],
                    linewidth=2, linestyle="--", marker="s", markersize=4)
            ax.fill_between(fore["year"], fore["yhat_lower"], fore["yhat_upper"],
                            alpha=0.15, color=colors[i])

        ax.set_title(dist[:14], color="#e6edf3", fontsize=9)
        ax.set_xlabel("Year", color="#8b949e", fontsize=8)

    plt.suptitle("Crime Forecast ??? Top 5 Districts", color="#e6edf3", fontsize=12, y=1.02)
    plt.tight_layout()
    out = PROC_DIR / "forecast_top5_districts.png"
    plt.savefig(out, dpi=120, bbox_inches="tight", facecolor="#0d1117")
    plt.close()
    print(f"  [CHART] {out}")


# ????????? Main ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def main():
    print("\n" + "="*60)
    print("  STEP 05 ??? Time Series Forecast (Prophet)")
    print("="*60)

    df = load_data()

    dist_col  = "DISTRICT" if "DISTRICT" in df.columns else df.columns[1]
    year_col  = "YEAR"     if "YEAR"     in df.columns else "year"
    crime_col = "TOTAL_CRIMES" if "TOTAL_CRIMES" in df.columns else df.select_dtypes("number").columns[0]

    print(f"  District col: {dist_col} | Year col: {year_col} | Crime col: {crime_col}")

    districts    = df[dist_col].dropna().unique()
    all_results  = []

    func = prophet_forecast if PROPHET_AVAILABLE else linear_forecast
    mode = "Prophet" if PROPHET_AVAILABLE else "Linear"
    print(f"  Forecasting {len(districts)} districts using {mode}...")

    for i, dist in enumerate(districts):
        subset = df[df[dist_col] == dist].sort_values(year_col)
        years  = subset[year_col]
        series = pd.to_numeric(subset[crime_col], errors="coerce").fillna(0)

        if len(series) < MIN_DATA_POINTS:
            continue

        result = func(dist, series, years, FORECAST_YEARS)
        if result.empty:
            continue

        # Add trend
        hist_avg = series.mean()
        fore_vals = result.loc[result["is_forecast"], "yhat"]
        result["TREND"] = classify_trend(fore_vals, hist_avg)

        all_results.append(result)

        if (i+1) % 10 == 0:
            print(f"    ... {i+1}/{len(districts)}")

    if not all_results:
        print("  [ERROR] No forecast data generated.")
        return

    combined = pd.concat(all_results, ignore_index=True)
    combined["yhat"]       = combined["yhat"].clip(lower=0).round(1)
    combined["yhat_lower"] = combined["yhat_lower"].clip(lower=0).round(1)
    combined["yhat_upper"] = combined["yhat_upper"].clip(lower=0).round(1)

    out = PROC_DIR / "crime_forecast.csv"
    combined.to_csv(out, index=False)
    print(f"  [OUT] {out}  ({len(combined)} rows, {combined['DISTRICT'].nunique()} districts)")

    # Emerging threats
    threats = (
        combined[combined["is_forecast"] & (combined["TREND"] == "INCREASING")]
        ["DISTRICT"].unique()
    )
    print(f"  [EMERGING THREATS] {len(threats)} districts with increasing trend: {list(threats[:5])}")

    # Chart
    save_forecast_chart(combined)

    print("\n  [DONE] Forecasting complete.")
    print("="*60 + "\n")


if __name__ == "__main__":
    main()

