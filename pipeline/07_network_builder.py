import pandas as pd
import numpy as np
import json
import warnings
warnings.filterwarnings("ignore")
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import seaborn as sns
from pathlib import Path

try:
    from pyvis.network import Network
    PYVIS_AVAILABLE = True
except ImportError:
    PYVIS_AVAILABLE = False
    print("  [WARN] pyvis not installed. HTML graph will be skipped.")

import networkx as nx

# ????????? Paths ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
ROOT     = Path(__file__).resolve().parent.parent
PROC_DIR = ROOT / "data" / "processed"

CORR_THRESHOLD = 0.70   # Only edges with |correlation| >= this value

CRIME_COLS = [
    "MURDER", "RAPE", "KIDNAPPING_ABDUCTION", "DACOITY", "ROBBERY",
    "BURGLARY", "THEFT", "AUTO_THEFT", "CHEATING", "ARSON",
    "DOWRY_DEATHS", "ASSAULT_ON_WOMEN_WITH_INTENT_TO_OUTRAGE_HER_MODESTY",
    "CRUELTY_BY_HUSBAND_OR_HIS_RELATIVES", "RIOTS", "CAUSING_DEATH_BY_NEGLIGENCE",
    "HURT_GREVIOUS_HURT", "CRIMINAL_BREACH_OF_TRUST", "COUNTERFIETING",
]

NODE_GROUPS = {
    "MURDER":                   ("Violent", "#f85149"),
    "RAPE":                     ("Violent", "#f85149"),
    "KIDNAPPING_ABDUCTION":     ("Violent", "#f85149"),
    "DACOITY":                  ("Violent", "#f85149"),
    "ROBBERY":                  ("Violent", "#f85149"),
    "ARSON":                    ("Violent", "#f85149"),
    "BURGLARY":                 ("Property", "#e3b341"),
    "THEFT":                    ("Property", "#e3b341"),
    "AUTO_THEFT":               ("Property", "#e3b341"),
    "CHEATING":                 ("Property", "#e3b341"),
    "CRIMINAL_BREACH_OF_TRUST": ("Property", "#e3b341"),
    "COUNTERFIETING":           ("Property", "#e3b341"),
    "DOWRY_DEATHS":             ("Women", "#bc8cff"),
    "ASSAULT_ON_WOMEN_WITH_INTENT_TO_OUTRAGE_HER_MODESTY": ("Women", "#bc8cff"),
    "CRUELTY_BY_HUSBAND_OR_HIS_RELATIVES":                 ("Women", "#bc8cff"),
    "RIOTS":                    ("Social", "#58a6ff"),
    "CAUSING_DEATH_BY_NEGLIGENCE": ("Social", "#58a6ff"),
    "HURT_GREVIOUS_HURT":       ("Social", "#58a6ff"),
}

# ????????? Load ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def load_data() -> pd.DataFrame:
    for fname in ["district_features.csv", "karnataka_clean.csv", "risk_scores.csv"]:
        p = PROC_DIR / fname
        if p.exists():
            print(f"  [DATA] Loading {fname}")
            return pd.read_csv(p, low_memory=False)
    raise FileNotFoundError("No district data found. Run 02_feature_engineering.py first.")


# ????????? Correlation Matrix ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def compute_correlation(df: pd.DataFrame) -> pd.DataFrame:
    available = [c for c in CRIME_COLS if c in df.columns]
    print(f"  [COLS] {len(available)} crime type columns found")
    return df[available].fillna(0).corr()


# ????????? NetworkX Graph ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def build_graph(corr: pd.DataFrame, df: pd.DataFrame) -> nx.Graph:
    G = nx.Graph()
    crime_totals = df[[c for c in CRIME_COLS if c in df.columns]].sum()

    # Add nodes
    for col in corr.columns:
        group, color = NODE_GROUPS.get(col, ("Other", "#8b949e"))
        G.add_node(
            col,
            label=col.replace("_", " ").title()[:20],
            group=group,
            color=color,
            size=int(np.log1p(crime_totals.get(col, 1)) * 3 + 8),
        )

    # Add edges where |corr| >= threshold
    cols = list(corr.columns)
    for i in range(len(cols)):
        for j in range(i+1, len(cols)):
            c = corr.iloc[i, j]
            if abs(c) >= CORR_THRESHOLD:
                G.add_edge(cols[i], cols[j], weight=round(abs(c), 2),
                           title=f"r = {c:.2f}",
                           color="#f85149" if c > 0 else "#58a6ff")

    print(f"  [GRAPH] {G.number_of_nodes()} nodes, {G.number_of_edges()} edges")
    return G


# ????????? Pyvis Interactive Graph ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def build_pyvis_html(G: nx.Graph) -> str:
    net = Network(
        height="600px", width="100%",
        bgcolor="#0d1117", font_color="#e6edf3",
        notebook=False,
    )
    net.from_nx(G)

    # Physics settings for better layout
    net.set_options("""{
      "physics": {
        "barnesHut": {"gravitationalConstant": -8000, "centralGravity": 0.3, "springLength": 120},
        "minVelocity": 0.75
      },
      "interaction": {"hover": true, "tooltipDelay": 200}
    }""")

    out = PROC_DIR / "crime_network.html"
    net.save_graph(str(out))
    return str(out)


# ????????? JSON Export (for API) ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def export_graph_json(G: nx.Graph):
    data = {
        "nodes": [
            {
                "id": n,
                "label": G.nodes[n].get("label", n),
                "group": G.nodes[n].get("group", "Other"),
                "color": G.nodes[n].get("color", "#8b949e"),
                "size":  G.nodes[n].get("size", 10),
            }
            for n in G.nodes
        ],
        "edges": [
            {
                "from":   u,
                "to":     v,
                "weight": G.edges[u,v].get("weight", 0),
                "color":  G.edges[u,v].get("color", "#555555"),
                "title":  G.edges[u,v].get("title", ""),
            }
            for u, v in G.edges
        ],
    }
    out = PROC_DIR / "crime_network_data.json"
    with open(out, "w") as f:
        json.dump(data, f, indent=2)
    print(f"  [JSON] {out}")


# ????????? Static Heatmap ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def save_correlation_heatmap(corr: pd.DataFrame):
    fig, ax = plt.subplots(figsize=(12, 10))
    fig.patch.set_facecolor("#0d1117")
    ax.set_facecolor("#0d1117")

    short_names = {c: c.replace("_", " ")[:14] for c in corr.columns}
    corr_renamed = corr.rename(index=short_names, columns=short_names)

    sns.heatmap(
        corr_renamed, annot=True, fmt=".2f", cmap="RdYlGn",
        center=0, ax=ax, linewidths=0.3, linecolor="#30363d",
        annot_kws={"size": 7},
        xticklabels=True, yticklabels=True,
    )
    ax.tick_params(colors="#8b949e", labelsize=7)
    ax.set_title("Crime Type Co-occurrence Correlation Matrix", color="#e6edf3", fontsize=13, pad=15)
    plt.setp(ax.get_xticklabels(), rotation=45, ha="right", color="#8b949e")
    plt.setp(ax.get_yticklabels(), rotation=0, color="#8b949e")

    plt.tight_layout()
    out = PROC_DIR / "crime_correlation.png"
    plt.savefig(out, dpi=120, bbox_inches="tight", facecolor="#0d1117")
    plt.close()
    print(f"  [CHART] {out}")


# ????????? Main ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def main():
    print("\n" + "="*60)
    print("  STEP 07 ??? Crime Network Graph Builder")
    print("="*60)

    df = load_data()
    print(f"  [DATA] Shape: {df.shape}")

    corr = compute_correlation(df)
    G    = build_graph(corr, df)

    # Pyvis interactive HTML
    if PYVIS_AVAILABLE:
        path = build_pyvis_html(G)
        print(f"  [GRAPH] {path}")
    else:
        print("  [SKIP] Pyvis not available ??? install with: pip install pyvis")

    # JSON for API
    export_graph_json(G)

    # Static heatmap
    save_correlation_heatmap(corr)

    # Print top connected crime types
    print("\n  Top 5 most connected crime types:")
    degrees = sorted(G.degree(), key=lambda x: x[1], reverse=True)[:5]
    for node, deg in degrees:
        print(f"    {node:45s} ??? {deg} connections")

    print("\n  [DONE] Network graph complete.")
    print("="*60 + "\n")


if __name__ == "__main__":
    main()

