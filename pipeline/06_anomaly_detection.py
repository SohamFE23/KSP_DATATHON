import pandas as pd
import numpy as np
import warnings
warnings.filterwarnings("ignore")
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from pathlib import Path
from sklearn.ensemble import IsolationForest
from sklearn.preprocessing import StandardScaler

# ????????? Paths ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
ROOT     = Path(__file__).resolve().parent.parent
PROC_DIR = ROOT / "data" / "processed"

CONTAMINATION = 0.10   # Expect ~10% anomalies

FEATURE_CANDIDATES = [
    "MURDER", "RAPE", "KIDNAPPING_ABDUCTION", "DACOITY", "ROBBERY",
    "BURGLARY", "THEFT", "AUTO_THEFT", "CHEATING", "ARSON",
    "DOWRY_DEATHS", "ASSAULT_ON_WOMEN_WITH_INTENT_TO_OUTRAGE_HER_MODESTY",
    "CRUELTY_BY_HUSBAND_OR_HIS_RELATIVES",
    "VIOLENT_CRIME_INDEX", "WOMEN_CRIME_INDEX", "PROPERTY_CRIME_INDEX",
    "TOTAL_CRIMES", "CRIME_YOY_CHANGE",
]

# ????????? Load ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def load_data() -> pd.DataFrame:
    for fname in ["district_features.csv", "karnataka_clean.csv", "risk_scores.csv"]:
        p = PROC_DIR / fname
        if p.exists():
            print(f"  [DATA] Loading {fname}")
            return pd.read_csv(p, low_memory=False)
    raise FileNotFoundError("No district data found. Run 02_feature_engineering.py first.")


# ????????? Anomaly Detection ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def detect_anomalies(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()

    # Select available features
    features = [c for c in FEATURE_CANDIDATES if c in df.columns]
    if not features:
        raise ValueError("No suitable feature columns found for anomaly detection.")

    print(f"  [FEATURES] {len(features)} features used")

    X = df[features].fillna(0)
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X)

    iso = IsolationForest(
        n_estimators=200,
        contamination=CONTAMINATION,
        max_samples="auto",
        random_state=42,
        n_jobs=-1,
    )
    iso.fit(X_scaled)

    # -1 = anomaly, 1 = normal
    df["IS_ANOMALY"]    = (iso.predict(X_scaled) == -1).astype(int)
    df["ANOMALY_SCORE"] = (-iso.score_samples(X_scaled)).round(4)   # higher = more anomalous

    # Severity classification
    q80 = df.loc[df["IS_ANOMALY"]==1, "ANOMALY_SCORE"].quantile(0.8)
    def severity(row):
        if row["IS_ANOMALY"] == 0: return "NORMAL"
        if row["ANOMALY_SCORE"] >= q80: return "CRITICAL"
        return "HIGH"

    df["ANOMALY_SEVERITY"] = df.apply(severity, axis=1)

    total = df["IS_ANOMALY"].sum()
    critical = (df["ANOMALY_SEVERITY"] == "CRITICAL").sum()
    pct = round(total / len(df) * 100, 1)
    print(f"  [ANOMALIES] {total} flagged ({pct}%)  |  {critical} CRITICAL")

    return df


# ????????? Chart ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def save_anomaly_chart(df: pd.DataFrame):
    dist_col  = "DISTRICT"      if "DISTRICT"      in df.columns else df.columns[1]
    year_col  = "YEAR"          if "YEAR"          in df.columns else "year"
    crime_col = "TOTAL_CRIMES"  if "TOTAL_CRIMES"  in df.columns else None

    fig, axes = plt.subplots(1, 2, figsize=(14, 5))
    fig.patch.set_facecolor("#0d1117")

    # ?????? Chart 1: Anomaly score distribution ??????????????????????????????????????????????????????????????????????????????????????????????????????
    ax = axes[0]
    ax.set_facecolor("#161b22")
    normal   = df.loc[df["IS_ANOMALY"]==0, "ANOMALY_SCORE"]
    anomalies = df.loc[df["IS_ANOMALY"]==1, "ANOMALY_SCORE"]

    ax.hist(normal,   bins=30, color="#3fb950", alpha=0.7, label="Normal")
    ax.hist(anomalies, bins=30, color="#f85149", alpha=0.7, label="Anomaly")
    ax.set_title("Anomaly Score Distribution", color="#e6edf3", fontsize=12)
    ax.set_xlabel("Anomaly Score (higher = more anomalous)", color="#8b949e")
    ax.set_ylabel("Count", color="#8b949e")
    ax.tick_params(colors="#8b949e")
    ax.legend(facecolor="#161b22", edgecolor="#30363d", labelcolor="#e6edf3")
    for sp in ax.spines.values(): sp.set_color("#30363d")

    # ?????? Chart 2: Top 15 anomalous district-years ???????????????????????????????????????????????????????????????????????????????????????
    ax2 = axes[1]
    ax2.set_facecolor("#161b22")
    top_anom = df[df["IS_ANOMALY"]==1].nlargest(15, "ANOMALY_SCORE")
    if dist_col in top_anom.columns and year_col in top_anom.columns:
        labels = [f"{r[dist_col][:10]} ({int(r[year_col])})" for _, r in top_anom.iterrows()]
    else:
        labels = [str(i) for i in range(len(top_anom))]

    colors_bar = ["#f85149" if s=="CRITICAL" else "#e3b341"
                  for s in top_anom["ANOMALY_SEVERITY"]]
    ax2.barh(labels[::-1], top_anom["ANOMALY_SCORE"].values[::-1], color=colors_bar[::-1])
    ax2.set_title("Top Anomalous District-Years", color="#e6edf3", fontsize=12)
    ax2.set_xlabel("Anomaly Score", color="#8b949e")
    ax2.tick_params(colors="#8b949e", labelsize=7)
    for sp in ax2.spines.values(): sp.set_color("#30363d")
    ax2.grid(True, alpha=0.15, color="#30363d", axis="x")

    plt.tight_layout()
    out = PROC_DIR / "anomaly_results.png"
    plt.savefig(out, dpi=120, bbox_inches="tight", facecolor="#0d1117")
    plt.close()
    print(f"  [CHART] {out}")


# ????????? Main ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def main():
    print("\n" + "="*60)
    print("  STEP 06 ??? Anomaly Detection (IsolationForest)")
    print("="*60)

    df = load_data()
    print(f"  [DATA] Shape: {df.shape}")

    df = detect_anomalies(df)

    out = PROC_DIR / "anomaly_flagged.csv"
    df.to_csv(out, index=False)
    print(f"  [OUT] {out}")

    save_anomaly_chart(df)

    # Summary
    print("\n  Top 5 CRITICAL Anomalies:")
    dist_col = "DISTRICT" if "DISTRICT" in df.columns else df.columns[1]
    year_col = "YEAR"     if "YEAR"     in df.columns else df.columns[2]
    top = df[df["ANOMALY_SEVERITY"]=="CRITICAL"][[dist_col, year_col, "ANOMALY_SCORE"]].nlargest(5, "ANOMALY_SCORE")
    print(top.to_string(index=False))

    print("\n  [DONE] Anomaly detection complete.")
    print("="*60 + "\n")


if __name__ == "__main__":
    main()

